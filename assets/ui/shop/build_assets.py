pixels, chars = [], []
for index, (char, rows) in enumerate(sorted(GLYPHS.items())):
    x, y = (index % 16) * 8, (index // 16) * 10
    if isinstance(rows, str):
        rows = rows.split()
    for row, cells in enumerate(rows):
        for col, cell in enumerate(cells):
            if cell == '1':
                pixels.append(f'<rect x="{x+col}" y="{y+row}" width="1" height="1" fill="white"/>')
    advance = 4 if char == ' ' else 6
    chars.append(f'char id={ord(char)} x={x} y={y} width=5 height=7 xoffset=0 yoffset=0 xadvance={advance} page=0 chnl=15')
height = ((len(GLYPHS) + 15) // 16) * 10
svg('shop-font.svg', 128, height, ''.join(pixels))
(ROOT / 'shop-font.fnt').write_text(
    'info face="Citadel Pixel" size=8 bold=0 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=1 padding=0,0,0,0 spacing=0,0\n'
    f'common lineHeight=9 base=7 scaleW=128 scaleH={height} pages=1 packed=0\n'
    'page id=0 file="shop-font.svg"\n'
    f'chars count={len(chars)}\n' + '\n'.join(chars) + '\n', encoding='utf-8')

