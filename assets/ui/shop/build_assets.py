def svg(name, width, height, body):
    (ROOT / name).write_text(
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
        f'viewBox="0 0 {width} {height}" shape-rendering="crispEdges">{body}</svg>\n',
        encoding='utf-8')


def frame(name, fill, gold, light, inner):
    paths = []
    for inset, color in [(0, '#090e14'), (1, '#553a22'), (2, gold),
                         (3, light), (4, '#684728'), (5, inner), (6, fill)]:
        x, y, w, h = inset, inset, 196 - 2 * inset, 84 - 2 * inset
        d = f'M{x+7} {y}H{x+w-7}V{y+3}H{x+w-3}V{y+7}H{x+w}V{y+h-7}H{x+w-3}V{y+h-3}H{x+w-7}V{y+h}H{x+7}V{y+h-3}H{x+3}V{y+h-7}H{x}V{y+7}H{x+3}V{y+3}H{x+7}Z'
        paths.append(f'<path d="{d}" fill="{color}"/>')
    for x in [9, 185]:
        paths.append(f'<path d="M{x} 10h2v2h-2zM{x} 72h2v2h-2z" fill="{light}"/>')
    paths.append(f'<path d="M12 7h172v1H12z" fill="{gold}" opacity=".5"/>')
    svg(name, 196, 84, ''.join(paths))


